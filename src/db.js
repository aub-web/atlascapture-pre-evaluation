'use strict';

// Database access. Postgres everywhere, so local and hosted run the same SQL:
//   - Hosted (Netlify DB / any Postgres): set NETLIFY_DATABASE_URL or DATABASE_URL  → node-postgres pool
//   - Local: no URL set → PGlite (embedded Postgres) stored in DATA_DIR/pg
// Everything is async: q() returns rows, one() the first row, tx(fn) runs fn(client) in a transaction.

const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const team = require('./team');
const { HOSTED } = require('./env');

const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, '..', 'data');
const DATABASE_URL = process.env.NETLIFY_DATABASE_URL || process.env.DATABASE_URL || '';

const now = () => new Date().toISOString();

let backend = null; // { query(text, params) -> { rows, rowCount }, transaction(fn) }

function makePgBackend() {
  const { Pool } = require('pg');
  const pool = new Pool({ connectionString: DATABASE_URL, max: 3, idleTimeoutMillis: 10_000 });
  return {
    query: (text, params) => pool.query(text, params),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn({ query: (t, p) => client.query(t, p) });
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
  };
}

async function makePgliteBackend() {
  // Loaded by variable name so the Netlify function bundle doesn't include it.
  const pkg = '@electric-sql/pglite';
  const { PGlite } = require(pkg);
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const db = await PGlite.create(path.join(DATA_DIR, 'pg'));
  const wrap = (r) => ({ rows: r.rows, rowCount: r.affectedRows ?? r.rows.length });
  return {
    query: async (text, params) => wrap(await db.query(text, params)),
    transaction: (fn) => db.transaction((t) => fn({ query: async (text, params) => wrap(await t.query(text, params)) })),
  };
}


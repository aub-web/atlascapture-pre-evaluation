let readyPromise = null;
function ready() {
  readyPromise ||= (async () => {
    if (HOSTED && !DATABASE_URL) throw new Error('No database: enable Netlify DB for this site (NETLIFY_DATABASE_URL is not set)');
    backend = DATABASE_URL ? makePgBackend() : await makePgliteBackend();
    // Advisory lock so concurrent cold starts don't race on schema creation.
    await backend.transaction(async (c) => {
      await c.query('SELECT pg_advisory_xact_lock(724113)');
      for (const stmt of SCHEMA.split(';').map((s) => s.trim()).filter(Boolean)) await c.query(stmt);
    });
    await syncRosterFile();
    await seedStudios();
    await bootstrapAdmins();
  })().catch((err) => {
    readyPromise = null;
    throw err;
  });
  return readyPromise;
}

async function q(text, params = []) {
  await ready();
  return (await backend.query(text, params)).rows;
}
async function one(text, params = []) {
  return (await q(text, params))[0];
}
async function run(text, params = []) {
  await ready();
  return backend.query(text, params);
}
async function tx(fn) {
  await ready();
  return backend.transaction(async (c) =>
    fn({
      q: async (t, p = []) => (await c.query(t, p)).rows,
      one: async (t, p = []) => (await c.query(t, p)).rows[0],
      run: (t, p = []) => c.query(t, p),
    }));
}

// ---------- Roster ----------
// The roster (studios, QC team, admins) comes from config/team.js (local) or is imported on the
// Team page (hosted). It syncs by email (then name): updates role/studio, adds new people and, when
// asked, deactivates roster people no longer listed. People added in the app are left alone.

function flattenRoster({ STUDIOS = [], QC_TEAM = [], ADMIN_TEAM = [] }) {
  return [
    ...STUDIOS.flatMap((s) => (s.members || []).map(([name, email, role]) => ({ name, email, role, studio: s.name }))),
    ...QC_TEAM.map(([name, email]) => ({ name, email, role: 'QC', studio: null })),
    ...ADMIN_TEAM.map(([name, email, title]) => ({ name, email, role: 'ADMIN', studio: null, title })),
  ]
    .filter((r) => r.name && ['SD', 'SPC', 'SPL', 'QC', 'ADMIN'].includes(r.role))
    .map((r) => ({ ...r, name: String(r.name).trim(), email: r.email ? String(r.email).trim().toLowerCase() : null, title: r.title ?? null }));
}

async function syncRoster(roster, { deactivateMissing }) {
  const people = flattenRoster(roster);
  const apply = async (c) => {
    const keep = new Set();
    let added = 0, updated = 0, deactivated = 0;
    for (const r of people) {
      const existing = (r.email && (await c.one('SELECT id FROM users WHERE lower(email) = $1', [r.email]))) ||
        (await c.one('SELECT id FROM users WHERE name = $1', [r.name]));
      if (existing && !keep.has(existing.id)) {
        await c.run("UPDATE users SET name = $1, email = $2, role = $3, studio = $4, title = $5, active = 1, source = 'roster' WHERE id = $6",
          [r.name, r.email, r.role, r.studio, r.title, existing.id]);
        keep.add(existing.id);
        updated++;
      } else {
        const row = await c.one('INSERT INTO users (name, email, role, studio, title) VALUES ($1, $2, $3, $4, $5) RETURNING id',
          [r.name, r.email, r.role, r.studio, r.title]);
        keep.add(row.id);
        added++;
      }
    }
    if (deactivateMissing) {
      for (const { id } of await c.q("SELECT id FROM users WHERE active = 1 AND source = 'roster'")) {
        if (!keep.has(id)) {
          await c.run('UPDATE users SET active = 0 WHERE id = $1', [id]);
          deactivated++;
        }
      }
    }
    // Studios with their country and city/region (dashboard filters, Google Sheet tab per country).
    for (const s of roster.STUDIOS || []) {
      if (!s.name) continue;
      await c.run(`INSERT INTO studios (name, region, country) VALUES ($1, $2, $3)
        ON CONFLICT (name) DO UPDATE SET region = COALESCE(EXCLUDED.region, studios.region), country = COALESCE(EXCLUDED.country, studios.country), active = 1`,
        [String(s.name).trim(), s.region ? String(s.region).trim() : null, s.country ? String(s.country).trim() : null]);
    }
    return { total: people.length, added, updated, deactivated };
  };
  // During startup the backend exists but ready() hasn't resolved yet, so go through it directly.
  return backend.transaction((c) => apply({
    q: async (t, p = []) => (await c.query(t, p)).rows,
    one: async (t, p = []) => (await c.query(t, p)).rows[0],
    run: (t, p = []) => c.query(t, p),
  }));
}

// Local roster file: synced when its contents change (hash stored in meta).
async function syncRosterFile() {
  if (team.hosted) return; // hosted: the roster is imported on the Team page
  if (team.isExample && (await backend.query('SELECT COUNT(*)::int AS n FROM users')).rows[0].n > 0) return;
  const roster = { STUDIOS: team.STUDIOS, QC_TEAM: team.QC_TEAM, ADMIN_TEAM: team.ADMIN_TEAM };
  // 'v2': bumped when the sync starts writing new data (studios), so existing databases re-sync once.
  const hash = crypto.createHash('sha256').update('v2' + JSON.stringify(roster)).digest('hex');
  const prev = (await backend.query("SELECT value FROM meta WHERE key = 'roster_hash'")).rows[0];
  if (prev?.value === hash) return;
  await syncRoster(roster, { deactivateMissing: !team.isExample });
  await backend.query("INSERT INTO meta (key, value) VALUES ('roster_hash', $1) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value", [hash]);
}

// Makes sure every studio people belong to has a row in `studios`. Databases created before the
// studios table carried countries in meta.studio_countries; those are copied over once.
async function seedStudios() {
  const legacy = JSON.parse((await backend.query("SELECT value FROM meta WHERE key = 'studio_countries'")).rows[0]?.value || '{}');
  await backend.query(`INSERT INTO studios (name) SELECT DISTINCT studio FROM users WHERE studio IS NOT NULL
    ON CONFLICT (name) DO NOTHING`);
  for (const [name, country] of Object.entries(legacy)) {
    await backend.query('UPDATE studios SET country = $1 WHERE name = $2 AND country IS NULL', [country, name]);
  }
}

// BOOTSTRAP_ADMINS=email[,email]: makes sure these people exist as active admins, so the first
// admin can sign in on a fresh hosted database before any roster is imported.
async function bootstrapAdmins() {
  const emails = String(process.env.BOOTSTRAP_ADMINS || '').split(',').map((e) => e.trim().toLowerCase()).filter(Boolean);
  for (const email of emails) {
    const u = (await backend.query('SELECT id FROM users WHERE lower(email) = $1', [email])).rows[0];
    if (u) await backend.query("UPDATE users SET role = 'ADMIN', active = 1, login_approved = 1, access_request = NULL WHERE id = $1", [u.id]);
    else await backend.query("INSERT INTO users (name, email, role, source, login_approved) VALUES ($1, $2, 'ADMIN', 'manual', 1)", [email.split('@')[0], email]);
  }
}

